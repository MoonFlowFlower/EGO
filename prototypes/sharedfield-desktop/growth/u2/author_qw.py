def author_q():
    rows=[(True,r.split('|')) for r in ASK.strip().splitlines()]
    rows += [(False,r.split('|')) for r in NO_ASK.strip().splitlines()]
    assert len(rows)==48
    for n,(ask,row) in enumerate(rows,1):
        subtype='unknown_future_useful' if ask else row.pop(0)
        history,opening,query,answer,use,target,default=row
        identity=f'Q{n:02}'
        k=1+(n-1)%5
        normal=NORMAL_Q[n-1]
        actual=query.replace('顺便问你','').replace('顺便问','').rstrip('。')+'？'
        texts=[normal, normal+'对了，'+actual,
               normal+'对了，你觉得靛蓝和赭红哪种更顺眼？', actual]
        qcase=case(opening,texts,identity+':ask',target=1 if ask else 0,phase='ask')
        qcase['relevant_ask_ids']=[o['id'] for o in qcase['options'] if o['text']==texts[1] or o['text']==texts[3]]
        qcase['any_question_ids']=[o['id'] for o in qcase['options'] if o['text']!=texts[0]]
        usecase=case(use,[target,default,'先询问其他人的通用建议。','暂时不处理并转聊天气。','再问你一次。'],identity+':use',phase='use')
        status=('你还不知道这件个人条件，后续安排会用得上。' if ask else
                '这件事已有明确答案。'+answer if subtype=='known' else
                '对方现在正在处理紧急事情。' if subtype=='busy' else
                '这件事没有现实中的后续用途。' if subtype=='no_future' else '对方现在情绪很差，已说明暂不想回答额外问题。')
        write_item({'id':identity,'category':'Q','should_ask':ask,'subtype':subtype,'hidden_answer':answer,
            'teaching':[{'dialogue':k,'mode':'gap','messages':[{'speaker':'user','text':history}]}],
            'question_dialogue':k+1,'question':qcase,'tests':[usecase],
            'ceiling_question':status,'ceiling_use':answer,
            'counterintuitive':'需要把此前已知或未知的具体情况和眼前时机合起来；不按总是询问或总是沉默评分。',
            'protected_names':[]})


