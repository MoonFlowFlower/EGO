def main():
    folder=Path(__file__).parent/'candidates';folder.mkdir(parents=True,exist_ok=True)
    rows=[r.split('|') for r in DATA.strip().splitlines()]
    assert len(rows)==24
    for n,row in enumerate(rows,49):
        assert len(row)==10,(n,len(row))
        subtype,history,opening,normal,query,answer,use,target,default,ceiling=row
        ask=subtype=='unknown_future_useful';identity=f'Q{n:02}'
        # Busy examples remain before their explicitly stated end times.
        k=1 if subtype=='busy' else 1+(n-49)%5
        texts=[normal,normal+'对了，'+query,normal+'对了，你更喜欢靛蓝还是赭红？',query]
        question=case(opening,texts,identity+':ask',target=1 if ask else 0,phase='ask')
        question['relevant_ask_ids']=[o['id'] for o in question['options'] if o['text'] in (texts[1],texts[3])]
        question['any_question_ids']=[o['id'] for o in question['options'] if o['text']!=normal]
        item={'id':identity,'category':'Q','should_ask':ask,'subtype':subtype,'hidden_answer':answer,
            'teaching':[{'dialogue':k,'mode':'gap','messages':[{'speaker':'user','text':history}]}],
            'question_dialogue':k+1,'question':question,
            'tests':[case(use,[target,default,'先询问其他人的通用建议。','暂时不处理并转聊天气。','再问你一次。'],identity+':use',phase='use')],
            'ceiling_question':ceiling,'ceiling_use':answer,
            'counterintuitive':'判断依赖前次谈话的具体已知、未知或持续情境；先验是否已会选择必须实测，作者不作保证。'}
        item['protected_names']=protected_names(history)
        path=folder/(identity+'.json')
        if path.exists():raise ValueError('supplement_exists')
        path.write_bytes((json.dumps(item,ensure_ascii=False,indent=2)+'\n').encode())


if __name__=='__main__':main()
